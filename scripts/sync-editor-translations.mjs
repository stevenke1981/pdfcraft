import fs from 'node:fs';
import path from 'node:path';

// Static editor modules use the same reviewed catalogs as the React interface.
const directory = path.join(process.cwd(), 'public/direct-pdf-editor');
const keys = JSON.parse(fs.readFileSync(path.join(directory, 'translation-keys.json'), 'utf8'));
const catalogs = Object.fromEntries(fs.readdirSync('messages').filter(file => file.endsWith('.json')).map(file => [
  file.replace('.json', ''), JSON.parse(fs.readFileSync(path.join('messages', file), 'utf8')).directEditor,
]));
const output = '// Generated by scripts/sync-editor-translations.mjs from messages/*.json.\n' +
  `export const catalogs = ${JSON.stringify(catalogs)};\n` +
  `export const keys = ${JSON.stringify(keys)};\n`;
fs.writeFileSync(path.join(directory, 'translations.js'), output);
if (fs.existsSync('out/direct-pdf-editor')) fs.writeFileSync('out/direct-pdf-editor/translations.js', output);
console.log(`Synced ${Object.keys(catalogs).length} editor locales.`);
